/**
 * Video links deliberately point at a YouTube search for the story rather than a
 * hardcoded upload, so a removed or re-uploaded video never leaves a dead link.
 * Replace `watch()` with a curated upload URL per story when the channel is chosen.
 */
function watch(query: string): StoryVideo {
  return {
    label: 'Watch a full talk on this story',
    url: `https://www.youtube.com/results?search_query=${encodeURIComponent(query)}`,
  };
}

