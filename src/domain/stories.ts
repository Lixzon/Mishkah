export function storiesInSection(section: StorySectionId): Story[] {
  return STORIES.filter((story) => story.section === section).sort((a, b) => a.order - b.order);
}

export function searchStories(query: string, section: StorySectionId | 'all' = 'all'): Story[] {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return STORIES
    .filter((story) => section === 'all' || story.section === section)
    .filter((story) => {
      if (terms.length === 0) return true;
      const haystack = [
        story.title,
        story.subtitle,
        story.short,
        story.long.join(' '),
        ...(story.tags ?? []),
      ].join(' ').toLocaleLowerCase();
      return terms.every((term) => haystack.includes(term));
    })
    .sort((a, b) => a.section.localeCompare(b.section) || a.order - b.order);
}

/** Formatting helper shared by the story UI and the tests. */
export function quranRefLabel(ref: QuranRef): string {
  return ref.to && ref.to !== ref.from
    ? `Qur’an ${ref.surah}:${ref.from}–${ref.to}`
    : `Qur’an ${ref.surah}:${ref.from}`;
}
