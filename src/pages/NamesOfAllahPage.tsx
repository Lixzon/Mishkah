import { useRef, useState, useEffect } from 'react';
import { namesTimestamps } from '../data/namesTimestamps';

const AUDIO_URL = 'https://www.soundhelix.com/examples/mp3/SoundHelix-Song-1.mp3';

export default function NamesOfAllahPage() {
  const audioRef = useRef<HTMLAudioElement>(null);
  const [currentPlayingId, setCurrentPlayingId] = useState<number | null>(null);

  useEffect(() => {
    if (!audioRef.current) return;

    const handleTimeUpdate = () => {
      const currentTime = audioRef.current.currentTime;
      const activeTimestamp = namesTimestamps.find(
        (ts) => currentTime >= ts.startTime && currentTime < ts.startTime + 3
      );

      if (activeTimestamp) {
        setCurrentPlayingId(activeTimestamp.id);
      }
    };

    audioRef.current?.addEventListener('timeupdate', handleTimeUpdate);
    return () => {
      audioRef.current?.removeEventListener('timeupdate', handleTimeUpdate);
    };
  }, []);

  // Auto-scroll the active name into view
  useEffect(() => {
    if (currentPlayingId) {
      const element = document.getElementById(`name-${currentPlayingId}`);
      if (element) {
        element.scrollIntoView({ behavior: 'smooth', block: 'center' });
      }
    }
  }, [currentPlayingId]);

  const togglePlayPause = () => {
    if (!audioRef.current) return;
    if (audioRef.current.paused) {
      audioRef.current.play();
    } else {
      audioRef.current.pause();
    }
  };

  return (
    <div className="p-6">
      <h2 className="text-2xl font-bold mb-6">Asma ul Husna - 99 Names of Allah</h2>

      <div className="relative">
        <audio
          ref={audioRef}
          src={AUDIO_URL}
          style={{ display: 'none' }}
        />
        <button
          onClick={togglePlayPause}
          className="fixed bottom-6 right-6 z-10 rounded-full bg-accent text-onaccent p-2"
          aria-label="Play/Pause"
        >
          ▶️
        </button>
      </div>

      <div className="grid grid-cols-2 gap-4">
        {namesOfAllah.map((name) => {
          const isActive = currentPlayingId === name.id;
          const cardClass = isActive
            ? 'p-3 border rounded-lg bg-emerald-900/40 ring-2 ring-emerald-400 scale-105'
            : 'p-3 border rounded-lg bg-surface text-center';

          return (
            <div
              key={name.id}
              id={`name-${name.id}`}
              className={cardClass}
            >
              <p className="font-medium">{name.arabic}</p>
              <p className="text-sm mt-1 truncate">{name.transliteration}</p>
              <p className="text-caption text-muted-foreground mt-1">{name.meaning}</p>
            </div>
          );
        })}
      </div>

      <div className="mt-4">
        <p className="text-caption text-muted-foreground">
          Currently playing: {currentPlayingId ? `#${currentPlayingId}` : 'None'}
        </p>
      </div>
    </div>
  );
}